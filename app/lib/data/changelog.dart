import '../app_version.dart';

/// 一条版本记录 —— **面向用户**的更新说明，不是给开发者看的提交记录。
///
/// 写法要求（照用户的验收口径）：
///   * 说"加好了什么 / 修好了什么"，不说"重构了 X"；
///   * 每条一句话，用户能看懂；
///   * **只写有据可查的东西** —— 依据是 `docs/RELEASE-0.09.md`（0.09 的 10 条 +
///     文末「附录：0.10 改动」第 11~16 条）与 `docs/HANDOFF.md`（0.08 及更早的交接）。
///     文档里找不到依据的版本，宁可不写、也不替它编功能。
class ReleaseNote {
  const ReleaseNote({
    required this.version,
    this.date,
    this.status,
    required this.headline,
    required this.changes,
  });

  /// 版本号，例如 `0.10`。早期版本记录不全时允许是一个区间描述（见 kChangelog 末条）。
  final String version;

  /// 这一版有确切日期的才填；没有就不显示（不猜日期）。
  final String? date;

  /// 版本状态（如实说明），例如「当前版本（还没打包交付）」「早期版本（记录不全）」。
  /// 没有特别状态时为 null。
  final String? status;

  /// 一句话摘要：这一版最主要改了什么。
  final String headline;

  /// 这一版具体改了什么，每条一句话。
  final List<String> changes;

  /// 是不是当前正在跑的版本。
  ///
  /// 刻意与 `kAppVersion` 比较，而不是写死 `index == 0`：版本号一改（并补上新记录），
  /// 「当前版本」标记自己就跟着走了，不会出现"标记还留在上一版"。
  bool get isCurrent => version == kAppVersion;
}

